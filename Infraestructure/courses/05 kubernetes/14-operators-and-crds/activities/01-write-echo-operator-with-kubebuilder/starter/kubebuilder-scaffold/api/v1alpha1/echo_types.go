// +kubebuilder:object:generate=true
// +groupName=demo.academy.io
package v1alpha1

import (
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/apimachinery/pkg/runtime"
	"sigs.k8s.io/controller-runtime/pkg/scheme"
)

var (
	GroupVersion  = runtime.NewSchemeBuilder(addKnownTypes)
	SchemeBuilder = &scheme.Builder{GroupVersion: schemaGroupVersion}
	AddToScheme   = SchemeBuilder.AddToScheme
)

// EchoSpec defines the desired state of Echo.
type EchoSpec struct {
	// Message is the string that will be stored into the materialized ConfigMap.
	// +kubebuilder:validation:MinLength=1
	// +kubebuilder:validation:MaxLength=256
	Message string `json:"message"`
}

// EchoStatus defines the observed state of Echo.
type EchoStatus struct {
	// ObservedMessage is the message the controller actually applied.
	ObservedMessage string `json:"observedMessage,omitempty"`

	// LastReconciledAt is the timestamp of the last successful reconcile.
	LastReconciledAt *metav1.Time `json:"lastReconciledAt,omitempty"`

	// Conditions represent the latest available observations.
	Conditions []metav1.Condition `json:"conditions,omitempty"`
}

// +kubebuilder:object:root=true
// +kubebuilder:subresource:status
// +kubebuilder:printcolumn:name="Message",type="string",JSONPath=".spec.message"
// +kubebuilder:printcolumn:name="Observed",type="string",JSONPath=".status.observedMessage"
// +kubebuilder:printcolumn:name="Age",type="date",JSONPath=".metadata.creationTimestamp"
type Echo struct {
	metav1.TypeMeta   `json:",inline"`
	metav1.ObjectMeta `json:"metadata,omitempty"`

	Spec   EchoSpec   `json:"spec,omitempty"`
	Status EchoStatus `json:"status,omitempty"`
}

// +kubebuilder:object:root=true
type EchoList struct {
	metav1.TypeMeta `json:",inline"`
	metav1.ListMeta `json:"metadata,omitempty"`
	Items           []Echo `json:"items"`
}


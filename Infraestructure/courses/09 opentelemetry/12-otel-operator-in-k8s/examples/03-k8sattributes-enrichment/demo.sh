#!/usr/bin/env bash
# Demo: show k8sattributes auto-attaching k8s.* resource attributes to spans
# sent from a Pod. The sender (telemetrygen) never sets those attributes.
#
# NOTE: no `set -o pipefail` on purpose.

set -eu

CLUSTER="otel-12-ex03"
HERE="$(cd "$(dirname "$0")" && pwd)"
CM_VERSION="v1.15.0"
OTEL_OP_URL="https://github.com/open-telemetry/opentelemetry-operator/releases/latest/download/opentelemetry-operator.yaml"
SCRATCH="/tmp/otel-12-ex03"

need() {
  if ! command -v "$1" >/dev/null 2>&1; then
    echo "SKIP: '$1' not installed; this demo requires kind + kubectl."
    exit 0
  fi
}

cleanup() {
  rm -rf "$SCRATCH"
  if [ "${KEEP:-0}" != "1" ]; then
    echo "== cleanup: deleting kind cluster '$CLUSTER' =="
    kind delete cluster --name "$CLUSTER" >/dev/null 2>&1 || true
  fi
}
trap cleanup EXIT

need kind
need kubectl
mkdir -p "$SCRATCH"

if ! kind get clusters 2>/dev/null | grep -qx "$CLUSTER"; then
  echo "== creating kind cluster '$CLUSTER' =="
  kind create cluster --name "$CLUSTER" --wait 90s >/dev/null
fi

echo "== installing cert-manager + OTel Operator =="
kubectl apply -f "https://github.com/cert-manager/cert-manager/releases/download/${CM_VERSION}/cert-manager.yaml" >/dev/null
kubectl -n cert-manager wait --for=condition=Available --timeout=180s deploy --all >/dev/null
kubectl apply -f "$OTEL_OP_URL" >/dev/null
kubectl -n opentelemetry-operator-system wait --for=condition=Available --timeout=180s deploy --all >/dev/null

echo "== applying enricher Collector =="
kubectl create ns observability --dry-run=client -o yaml | kubectl apply -f - >/dev/null
kubectl apply -f "$HERE/collector-k8sattrs.yaml"
for _ in $(seq 1 30); do
  kubectl -n observability get deploy enricher-collector >/dev/null 2>&1 && break
  sleep 2
done
kubectl -n observability rollout status deploy/enricher-collector --timeout=120s

echo "== RBAC generated by the Operator for k8sattributes =="
kubectl get clusterrole -l app.kubernetes.io/managed-by=opentelemetry-operator -o name | head -3 || true

echo "== running telemetrygen Job =="
kubectl create ns demo --dry-run=client -o yaml | kubectl apply -f - >/dev/null
kubectl apply -f "$HERE/telemetrygen-job.yaml"
kubectl -n demo wait --for=condition=Complete --timeout=120s job/telemetrygen-traces || true

echo "== Collector logs — look for k8s.* resource attributes =="
kubectl -n observability logs deploy/enricher-collector --tail=80 | grep -E 'k8s\.(pod|namespace|node|deployment)\.name|Span #|Resource attributes' || true

echo
echo "Lesson: the Job never set k8s.* attributes. The processor correlated the"
echo "        source IP of the OTLP connection with the Pod via the API server"
echo "        watch, then attached pod/namespace/node metadata to every span."
